"""
Module: analytics/surge_calculator.py
Description: Demand Surge Analytics & Synthesis Engine.
             Combines historical hourly MapReduce baseline pickups with Kafka real-time
             streaming window counts to compute estimated pickup-demand surge ratios
             and rank the Top 10 high-demand taxi zones.
Author: Big Data Senior Engineer & Project Mentor
"""

import sys
import json
import logging
from pathlib import Path
from typing import Optional, Tuple
import pandas as pd
import yaml

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)]
)
logger = logging.getLogger(__name__)


def load_config() -> dict:
    """Loads configuration from configs/app_config.yaml."""
    base_dir = Path(__file__).resolve().parent.parent
    config_path = base_dir / "configs" / "app_config.yaml"
    with open(config_path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


class SurgeAnalyticsEngine:
    """
    Synthesizes historical MapReduce baselines with streaming Kafka counts.
    Ensures mathematical transparency and graceful edge-case handling.
    """

    def __init__(self, config: Optional[dict] = None):
        self.config = config or load_config()
        self.base_dir = Path(__file__).resolve().parent.parent
        self.smoothing_epsilon = float(self.config["analytics"].get("smoothing_epsilon", 1.0))
        self.surge_thresh_high = float(self.config["analytics"].get("surge_threshold_high", 1.5))
        self.surge_thresh_mod = float(self.config["analytics"].get("surge_threshold_moderate", 1.2))
        self.top_n = int(self.config["analytics"].get("top_n_rank_count", 10))

    def load_zone_lookup(self) -> pd.DataFrame:
        """Loads official TLC taxi zone reference lookup table."""
        path = self.base_dir / self.config["storage"]["lookup_csv"]
        if not path.exists():
            raise FileNotFoundError(f"Missing zone lookup CSV at {path}")
        df = pd.read_csv(path)
        return df[["LocationID", "Borough", "Zone", "service_zone"]]

    def load_historical_baseline(self) -> pd.DataFrame:
        """Loads the MapReduce-generated historical hourly baseline."""
        path = self.base_dir / self.config["storage"]["historical_baseline_csv"]
        if not path.exists():
            raise FileNotFoundError(f"Missing MapReduce baseline CSV at {path}")
        return pd.read_csv(path)

    def load_streaming_window(self) -> dict:
        """Loads the current rolling-window snapshot generated by Kafka consumer."""
        path = self.base_dir / "data" / "processed" / "live_window_pickups.json"
        if not path.exists():
            logger.warning(f"No streaming window snapshot found at {path}. Returning empty state.")
            return {
                "last_updated": None,
                "window_duration_minutes": 15,
                "total_window_events": 0,
                "active_zones_count": 0,
                "data_freshness": "NO_DATA",
                "zone_counts": {}
            }
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)

    def compute_surge_metrics(
        self,
        target_hour: Optional[int] = None,
        streaming_snapshot: Optional[dict] = None
    ) -> Tuple[pd.DataFrame, pd.DataFrame]:
        """
        Synthesizes baseline and streaming counts for all 265 zones at target_hour.
        Returns:
            (master_synthesis_df, top_10_ranked_df)
        """
        zone_lookup = self.load_zone_lookup()
        baseline_df = self.load_historical_baseline()
        snapshot = streaming_snapshot if streaming_snapshot is not None else self.load_streaming_window()

        # If target_hour not provided, infer from latest streaming timestamp or default to 14:00
        if target_hour is None:
            latest_time_str = snapshot.get("event_window_latest_time")
            if latest_time_str:
                try:
                    target_hour = pd.to_datetime(latest_time_str).hour
                except Exception:
                    target_hour = 14
            else:
                target_hour = 14

        logger.info(f"Computing surge analytics for Target Hour: {target_hour:02d}:00 (Window: {snapshot.get('window_duration_minutes', 15)}m)")

        # Filter baseline for the target hour
        hour_baseline = baseline_df[baseline_df["hour"] == target_hour].copy()

        # Merge with master zone lookup to guarantee all 265 zones are accounted for (cold-start resilience)
        master = pd.merge(
            zone_lookup,
            hour_baseline[["LocationID", "total_pickups", "baseline_pickups"]],
            on="LocationID",
            how="left"
        )
        master["total_pickups"] = master["total_pickups"].fillna(0).astype(int)
        master["baseline_pickups"] = master["baseline_pickups"].fillna(0.0).round(2)
        master["hour"] = target_hour

        # Compute expected baseline pickups scaled to the 15-minute streaming window
        window_minutes = snapshot.get("window_duration_minutes", 15)
        window_fraction = window_minutes / 60.0
        master["expected_window_pickups"] = (master["baseline_pickups"] * window_fraction).round(2)

        # Attach live streaming window pickup counts
        live_counts = snapshot.get("zone_counts", {})
        master["live_window_pickups"] = master["LocationID"].apply(
            lambda loc_id: live_counts.get(str(loc_id), 0)
        )

        # Transparent Surge Ratio Formula:
        # Surge Ratio = live_window_pickups / (expected_window_pickups + epsilon)
        master["surge_ratio"] = (
            master["live_window_pickups"] / (master["expected_window_pickups"] + self.smoothing_epsilon)
        ).round(2)

        # Categorize surge status
        def categorize(row):
            ratio = row["surge_ratio"]
            live = row["live_window_pickups"]
            if live == 0:
                return "No Observed Pickups"
            if ratio >= self.surge_thresh_high and live >= 3:
                return "High Pickup Surge"
            if ratio >= self.surge_thresh_mod and live >= 2:
                return "Moderate Surge"
            if ratio >= 0.8:
                return "Normal Activity"
            return "Below Average Activity"

        master["surge_category"] = master.apply(categorize, axis=1)

        # Telematics / AVL driver supply disclaimer
        master["unmet_demand_status"] = "UNMEASURED (Driver AVL supply unavailable in TLC records)"

        # Sort and rank all zones by surge ratio (descending) and live pickups (descending)
        master = master.sort_values(
            by=["surge_ratio", "live_window_pickups", "expected_window_pickups"],
            ascending=[False, False, False]
        ).reset_index(drop=True)

        master["surge_rank"] = master.index + 1

        # Extract Top N Zones with active demand
        top_n_df = master[master["live_window_pickups"] > 0].head(self.top_n).copy()
        if len(top_n_df) < self.top_n:
            top_n_df = master.head(self.top_n).copy()

        return master, top_n_df

    def run_synthesis_pipeline(
        self,
        target_hour: Optional[int] = None
    ) -> Tuple[Path, Path]:
        """Runs the synthesis pipeline and writes output CSV and JSON files."""
        master_df, top_10_df = self.compute_surge_metrics(target_hour=target_hour)

        out_master_csv = self.base_dir / "data" / "processed" / "current_demand_heatmap.csv"
        out_top10_csv = self.base_dir / "data" / "processed" / "top_10_demand_zones.csv"
        out_summary_json = self.base_dir / "data" / "processed" / "surge_analytics_summary.json"

        out_master_csv.parent.mkdir(parents=True, exist_ok=True)
        master_df.to_csv(out_master_csv, index=False)
        top_10_df.to_csv(out_top10_csv, index=False)

        summary = {
            "target_hour": int(master_df["hour"].iloc[0]),
            "total_official_zones": len(master_df),
            "zones_with_live_pickups": int((master_df["live_window_pickups"] > 0).sum()),
            "high_surge_zones_count": int((master_df["surge_category"] == "High Pickup Surge").sum()),
            "moderate_surge_zones_count": int((master_df["surge_category"] == "Moderate Surge").sum()),
            "top_surge_zone": {
                "LocationID": int(top_10_df["LocationID"].iloc[0]),
                "Zone": str(top_10_df["Zone"].iloc[0]),
                "Borough": str(top_10_df["Borough"].iloc[0]),
                "surge_ratio": float(top_10_df["surge_ratio"].iloc[0]),
                "live_pickups": int(top_10_df["live_window_pickups"].iloc[0]),
            }
        }

        with open(out_summary_json, "w", encoding="utf-8") as f:
            json.dump(summary, f, indent=2)

        logger.info(f"Demand heatmap synthesis saved: {out_master_csv.name} ({len(master_df)} zones)")
        logger.info(f"Top 10 leaderboard saved: {out_top10_csv.name}")
        logger.info(f"Summary metrics saved: {out_summary_json.name}")

        return out_master_csv, out_top10_csv


if __name__ == "__main__":
    engine = SurgeAnalyticsEngine()
    engine.run_synthesis_pipeline()
